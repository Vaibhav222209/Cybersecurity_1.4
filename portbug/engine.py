def now():
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def number(record, name, default=0):
    value = record.get(name, default)
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        raise ValueError(f"{name} must be numeric")
    if not math.isfinite(value) or value < 0:
        raise ValueError(f"{name} must be finite and nonnegative")
    return value


def flag(record, name, default=False):
    value = record.get(name, default)
    if not isinstance(value, bool):
        raise ValueError(f"{name} must be true or false")
    return value


def detect(events):
    """Evaluate bounded event summaries against five explicit detection rules.

    Counts/windows must be supplied by a trusted collector in a real system.
    Here all inputs are generated by this module and intentionally synthetic.
    """
    if not isinstance(events, list) or len(events) > MAX_RECORDS:
        raise ValueError("events must be a list of at most 100 records")
    findings = []
    for event in events:
        if not isinstance(event, dict):
            raise ValueError("each event must be an object")
        kind = event.get("type")
        matched = False
        detail = ""
        if kind == "credential_abuse":
            count = number(event, "failures")
            window = number(event, "window_seconds")
            matched = count >= 8 and 0 < window <= 300
            detail = f"{count:g} failed sign-ins in {window:g}s for PB-DEMO-USER-014. Review identity and session evidence."
        elif kind == "payment_change":
            changed = flag(event, "beneficiary_changed")
            approved = flag(event, "dual_approval")
            matched = changed and not approved
            detail = "Synthetic beneficiary instructions changed without a second approval. No real payment exists."
        elif kind == "data_export":
            rows = number(event, "rows")
            baseline = number(event, "baseline_rows", 200)
            matched = rows >= 1000 and rows > max(baseline, 1) * 5
            detail = f"{rows:g} synthetic rows collected; expected baseline {baseline:g}. Validate business purpose."
        elif kind == "privilege_change":
            privileged = flag(event, "privileged")
            approved = flag(event, "approved")
            matched = privileged and not approved
            detail = "A synthetic identity received a privileged role without an approved change record."
        elif kind == "impossible_travel":
            distance = number(event, "distance_km")
            minutes = number(event, "elapsed_minutes")
            speed = distance / max(minutes / 60, 1 / 60)
            matched = distance >= 500 and speed > 900
            detail = f"Synthetic sessions imply {distance:g}km in {minutes:g} minutes. VPNs and shared accounts can produce false positives."
        elif kind not in {"baseline", None}:
            raise ValueError("unknown event type")
        if matched:
            finding = dict(RULES[kind])
            finding.update(rule=kind, detail=detail, time=event.get("time", now()))
            findings.append(finding)
    return findings


def evaluate_fraud(transaction):
    """Return an advisory score with reproducible feature contributions."""
    if not isinstance(transaction, dict):
        raise ValueError("transaction must be an object")
    amount = number(transaction, "amount_chf")
    velocity = number(transaction, "velocity_count")
    distance = number(transaction, "distance_km")
    minutes = number(transaction, "minutes_since_previous", 60)
    fan_in = number(transaction, "fan_in_count")
    new_beneficiary = flag(transaction, "new_beneficiary")
    score = 0
    reasons = []
    if velocity >= 5:
        score += 30
        reasons.append("+30 · five or more transfers in the simulated 10-minute window")
    if amount >= 25000 and new_beneficiary:
        score += 35
        reasons.append("+35 · CHF 25,000+ to a new synthetic beneficiary")
    if distance >= 500 and distance / max(minutes / 60, 1 / 60) > 900:
        score += 25
        reasons.append("+25 · inconsistent synthetic location sequence")
    if fan_in >= 8:
        score += 30
        reasons.append("+30 · eight or more synthetic funding sources (fan-in signal)")
    return {
        "score": min(score, 100), "decision": "review" if score >= 45 else "allow",
        "reasons": reasons or ["No configured rule threshold exceeded"],
    }


def scenario_event(scenario):
    records = {
        "credential_abuse": {"failures": 14, "window_seconds": 180},
        "payment_change": {"beneficiary_changed": True, "dual_approval": False},
        "data_export": {"rows": 18000, "baseline_rows": 200},
        "privilege_change": {"privileged": True, "approved": False},
        "impossible_travel": {"distance_km": 5900, "elapsed_minutes": 42},
        "baseline": {},
    }
    if scenario not in records:
        raise ValueError("unknown scenario")
    return {"type": scenario, "time": now(), **records[scenario]}


def refresh(state):
    open_count = sum(a["status"] in {"open", "investigating"} for a in state["alerts"])
    contained = sum(a["status"] in {"contained", "resolved"} for a in state["alerts"])
    review_count = sum(t["decision"] == "review" for t in state["fraud"])
    state["as_of"] = now()
    state["metrics"] = [
        {"label": "Open investigations", "value": f"{open_count:02}", "detail": "Synthetic observations · requires triage", "tone": "amber"},
        {"label": "Containment actions", "value": f"{contained:02}", "detail": "Local workflow outcomes only", "tone": "green"},
        {"label": "Detection coverage", "value": "5", "detail": "Rule families · ATT&CK mapped", "tone": "cyan"},
        {"label": "Payments for review", "value": f"{review_count:02}", "detail": "Explainable synthetic fraud signals", "tone": "violet"},
    ]


def apply_scenario(state, scenario):
    event = scenario_event(scenario)
    findings = detect([event])
    for finding in findings:
        state["sequence"] += 1
        identifier = f"PB-{state['sequence']:04d}"
        state["alerts"].insert(0, {
            "id": identifier, "status": "open", **finding,
        })
        state["incidents"].insert(0, {
            "id": identifier, "title": finding["title"], "severity": finding["severity"],
            "status": "open", "owner": "Unassigned · local exercise",
            "steps": ["Preserve synthetic evidence", "Triage identity and business context", "Authorize simulated containment", "Verify recovery and document lessons"],
        })
    if scenario == "payment_change":
        transaction = {
            "amount_chf": 84500, "velocity_count": 7, "new_beneficiary": True,
            "distance_km": 5900, "minutes_since_previous": 42, "fan_in_count": 2,
        }
        state["fraud"].insert(0, {
            "id": f"TX-DEMO-{state['sequence']:04d}", "amount_chf": transaction["amount_chf"],
            "account": "PB-DEMO-ACCOUNT-014", **evaluate_fraud(transaction),
        })
    for name in ("alerts", "incidents", "fraud"):
        state[name] = state[name][:MAX_RECORDS]
    state["trend"][-1]["blocked"] += len(findings)
    state["trend"][-1]["reviewed"] += int(scenario == "baseline")
    refresh(state)
    return {
        "title": "Baseline evaluated" if scenario == "baseline" else "Scenario evaluated",
        "summary": f"{len(findings)} finding(s) from generated local events. No external system was contacted.",
        "alerts_created": len(findings), "scenario": scenario,
    }


def respond(state, alert_id, action):
    transitions = {"triage": ("open", "investigating"), "contain": ("investigating", "contained"), "resolve": ("contained", "resolved")}
    if action not in transitions:
        raise ValueError("unknown response action")
    alert = next((a for a in state["alerts"] if a["id"] == alert_id), None)
    if alert is None:
        raise ValueError("unknown alert")
    expected, target = transitions[action]
    if alert["status"] != expected:
        raise ValueError(f"{action} requires status {expected}")
    alert["status"] = target
    for incident in state["incidents"]:
        if incident["id"] == alert_id:
            incident["status"] = target
            incident["owner"] = "Local exercise operator"
    refresh(state)
    return {
        "title": f"Exercise status: {target}",
        "summary": f"{alert_id} moved to {target}. This updates synthetic workflow state only; no real account or token was changed.",
        "alert_id": alert_id, "action": action,
    }


